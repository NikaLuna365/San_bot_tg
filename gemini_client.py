import os
import logging
import asyncio
from typing import Any, Dict, List

from google.generativeai import GenerativeModel, configure, types

# Импортируем тексты вопросов из констант
from constants import WEEKDAY_FIXED_QUESTIONS, OPEN_QUESTIONS, RETRO_OPEN_QUESTIONS

logger = logging.getLogger(__name__)

# Настройка Gemini API ключа
API_KEY = os.getenv("GEMINI_API_KEY")
if not API_KEY:
    logger.warning("GEMINI_API_KEY не задан в переменных окружения. Функции AI не будут работать.")
    try:
        configure(api_key="DUMMY_KEY_NEEDS_REPLACEMENT")
    except Exception as e:
        logger.error(f"Failed to configure Gemini with dummy key: {e}")
else:
     try:
        configure(api_key=API_KEY)
        logger.info("Gemini API ключ успешно сконфигурирован.")
     except Exception as e:
        logger.error(f"Failed to configure Gemini with provided key: {e}")
        API_KEY = None

# Выбор модели (можно вынести в .env)
GEMINI_MODEL_NAME = os.getenv("GEMINI_MODEL_NAME", "gemini-1.5-flash")


# !!! ИЗМЕНЕНО: Переработан промпт для теста !!!
def build_gemini_prompt_for_test(fixed_questions: List[str], test_answers: Dict[str, Any]) -> str:
    """Строит промпт для Gemini на основе ответов на ежедневный тест."""
    prompt = (
        "Вы - эмпатичный и внимательный психолог-консультант. Ваш клиент только что прошёл ежедневный опрос для саморефлексии. Ваша задача - проанализировать его ответы и дать поддерживающую обратную связь.\n\n"
        "Инструкция для Вас:\n"
        "1.  **Анализ шкал:** Мысленно оцените три шкалы (Самочувствие (в. 1,2), Активность (в. 3,4), Настроение (в. 5,6)) по 7-балльной шкале (1-низкий, 7-высокий). НЕ НУЖНО выводить числовые значения или оценки (Низкая/Средняя/Высокая) в ответе.\n"
        "2.  **Эмпатичный отклик (1-2 предложения):** Начните ответ с прямого обращения к клиенту на 'Вы'. Кратко отразите общее впечатление от его состояния, опираясь на анализ шкал. Например: 'Похоже, Вы сегодня чувствуете себя довольно энергично, но настроение немного отстает' или 'Заметно, что сегодня Вам может быть непросто, судя по Вашим ответам'.\n"
        "3.  **Анализ открытых вопросов (2-3 предложения):** Интегрируйте ответы на открытые вопросы (7 и 8) в свой ответ. Свяжите их с общим состоянием. Проговорите то, что клиент сам написал, возможно, немного перефразируя. Например: 'Вы упомянули, что основное влияние оказала [событие из ответа 8], и описали свое состояние как [фразы из ответа 7]. Понимаю, как это может влиять на Ваше самочувствие/настроение...'\n"
        "4.  **Поддерживающий/Наводящий вопрос (1 вопрос):** Завершите ответ открытым вопросом, который поможет клиенту глубже задуматься или поделиться чувствами. Например: 'Что могло бы Вас поддержать сейчас?' или 'Хотите подробнее обсудить [тема из открытого ответа]?'.\n"
        "5.  **Тон:** Дружелюбный, поддерживающий, без формализма, без осуждения.\n"
        "6.  **Форматирование:** НЕ используйте markdown (*, _, `) или нумерованные/маркированные списки. Ответ должен быть единым текстом.\n\n"
        "Ответы клиента:\n"
    )
    # Добавляем фиксированные вопросы и ответы
    for i, question in enumerate(fixed_questions, start=1):
        key = f"fixed_{i}"
        answer = test_answers.get(key, "не указано")
        prompt += f"{i}. {question}\n   Ответ: {answer}\n"
    # Добавляем открытые вопросы и ответы
    for j, question in enumerate(OPEN_QUESTIONS, start=1):
        key = f"open_{j}"
        answer = test_answers.get(key, "не указано")
        prompt += f"{len(fixed_questions) + j}. {question}\n   Ответ: {answer}\n"

    logger.debug(f"Промпт для теста:\n{prompt}")
    return prompt

# !!! ИЗМЕНЕНО: Переработан промпт для ретроспективы !!!
def build_gemini_prompt_for_retro(
    averages: Dict[str, Any], test_count: int, open_answers: Dict[str, Any], period_days: int
) -> str:
    """Строит промпт для Gemini на основе данных ретроспективы."""
    prompt = (
        f"Вы - вдумчивый психолог-консультант. Ваш клиент подготовил ретроспективу своего состояния за последние {period_days} дней. Ваша задача - проанализировать предоставленные данные и дать развернутую, поддерживающую обратную связь.\n\n"
        "Данные от клиента:\n"
        f"*   Количество пройденных тестов: {test_count}.\n"
        "*   Средние показатели по шкалам (1-7):\n"
    )
    # Добавляем средние значения
    for key, value in averages.items():
        avg_value = round(value, 1) if value is not None else 'нет данных'
        prompt += f"    *   {key}: {avg_value}\n"

    prompt += "\n*   Ответы на качественные вопросы ретроспективы:\n"
    # Добавляем ответы на открытые вопросы ретроспективы
    for idx, question in enumerate(RETRO_OPEN_QUESTIONS, start=1):
        key = f"retro_open_{idx}"
        answer = open_answers.get(key, "не указано")
        prompt += f"    {idx}. {question}\n       Ответ: {answer}\n"

    prompt += (
        "\nИнструкция для Вас:\n"
        "1.  **Вступление (1 предложение):** Обратитесь к клиенту на 'Вы'. Поблагодарите за проделанную работу по рефлексии.\n"
        "2.  **Анализ Динамики (2-3 предложения):** Опираясь на средние показатели, опишите общую тенденцию состояния за период. Используйте эмпатичные формулировки. Например: 'Судя по средним оценкам, этот период был для Вас достаточно [стабильным/энергичным/непростым] в плане [самочувствия/активности/настроения]...' Отметьте как сильные стороны, так и возможные сложности.\n"
        "3.  **Анализ Качественных Ответов (3-4 предложения):** Глубоко проанализируйте ответы на открытые вопросы. Отразите ключевые моменты, которые упомянул клиент (события, факторы, ожидания, уроки). Покажите, что Вы внимательно прочитали и поняли его опыт. Например: 'Вы отметили, что [ключевое событие] особенно повлияло на Вас, и размышляли над тем, как [урок] можно использовать дальше. Здорово, что Вы замечаете эти связи.'\n"
        "4.  **Связь и Синтез (1-2 предложения):** Попробуйте связать количественные показатели с качественными ответами, если это уместно. Например: 'Возможно, [фактор из ответа] объясняет, почему [показатель] был [выше/ниже] в этот период?'\n"
        "5.  **Поддерживающие/Наводящие Вопросы (1-2 вопроса):** Задайте открытые вопросы, которые помогут клиенту продолжить рефлексию или сфокусироваться на будущем. Например: 'Что бы Вам хотелось изменить или на чем сфокусироваться на следующей неделе, учитывая этот опыт?' или 'Какие маленькие шаги могли бы помочь Вам [справиться с фактором Х/усилить фактор Y]?'.\n"
        "6.  **Тон:** Поддерживающий, вдумчивый, профессиональный, но человечный.\n"
        "7.  **Форматирование:** НЕ используйте markdown (*, _, `). Можно использовать абзацы для структурирования."
    )
    logger.debug(f"Промпт для ретроспективы:\n{prompt}")
    return prompt

